#!/usr/bin/env python3
"""m68k_mksrc.py: turns a raw 68000 memory image into a vasm source (Motorola
syntax) that must reassemble to the same bytes.

usage: m68k_mksrc.py IMAGE LOAD_ADDR OUT.s [--labels FILE] [--pointer-scan]
                     [--entry A ...] [--check VASM]
Code found by m68k_recdis.py becomes instructions; every branch target, pc-relative
and absolute .l operand inside the image becomes a label; everything else is
dc.b. An instruction whose text does not reassemble to its own bytes (Capstone
spelling vasm rejects, or an encoding vasm would choose differently) is emitted as
dc.w with the disassembly in a comment, and listed.
--check: assembles with `vasm -Fbin -no-opt` and compares with IMAGE.
Absolute values that are addresses but appear as immediates (#$...) or inside
data are NOT converted: the source is identical, not yet relocatable (shift test,
docs/03).
"""
import argparse
import os
import re
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import m68k_recdis as R  # noqa: E402


def vasm_syntax(m, ops):
    """Capstone text -> vasm text (spacing, a few spellings)"""
    ops = ops.replace(", ", ",")
    if m.startswith("illegal"):
        return "illegal", ""
    m = m.replace("dbra.w", "dbra")
    # absolute short addresses >= $8000 are sign-extended: vasm wants $FFFFxxxx.w
    ops = re.sub(r"(?<![#0-9a-f])\$([89a-f][0-9a-f]{3})\.w", lambda mm: "$ffff%s.w" % mm.group(1), ops)
    # bit instructions: the size follows from the operand (register: .l, memory: .b)
    if re.match(r"^b(tst|set|clr|chg)\.[bl]$", m):
        m = m.split(".")[0]
    # capstone writes "#$4afc" for illegal etc.; movem register lists are fine
    return m, ops


def assemble_one(vasm, text, org, tmp):
    """bytes produced by vasm for one instruction at org (labels not allowed)"""
    src = os.path.join(tmp, "one.s")
    out = os.path.join(tmp, "one.bin")
    open(src, "w").write("\torg\t$%x\n\t%s\n" % (org, text))
    r = subprocess.run([vasm, "-Fbin", "-no-opt", "-quiet", "-o", out, src],
                       stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    if r.returncode != 0 or not os.path.exists(out):
        return None
    return open(out, "rb").read()


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("image")
    ap.add_argument("load", type=lambda x: int(x, 0))
    ap.add_argument("out")
    ap.add_argument("--labels")
    ap.add_argument("--entry", action="append", type=lambda x: int(x, 0), default=[])
    ap.add_argument("--pointer-scan", action="store_true")
    ap.add_argument("--check", metavar="VASM")
    a = ap.parse_args()
    data = open(a.image, "rb").read()
    names, comments = R.load_labels(a.labels)
    dis = R.Disasm(data, a.load)
    dis.run([a.load] + a.entry + R.code_names(names))
    if a.pointer_scan:
        dis.pointer_scan()

    def label(x):
        if x in names:
            return names[x]
        return "L%06x" % x

    # every address referenced by code and inside the image gets a label
    targets = set(names)
    targets.update(t for t in dis.code_refs if dis.inside(t))
    for addr, (size, m, ops) in dis.ins.items():
        for x in dis.addresses(ops):
            if dis.inside(x):
                targets.add(x)
    # a label inside an instruction cannot be placed: keep those as numbers
    starts = set(dis.ins)
    inside_ins = set()
    for addr, (size, m, ops) in dis.ins.items():
        inside_ins.update(range(addr + 1, addr + size))
    targets = {t for t in targets if t not in inside_ins}

    def sub_ops(ops):
        def rep(mm):
            if mm.group(1):
                return mm.group(0)                      # immediate: a value
            x = int(mm.group(2), 16)
            suf = mm.group(3) or ""
            if suf == ".w" and x >= 0x8000:
                return mm.group(0)                      # sign-extended: hardware
            if x in targets:
                return label(x) + suf
            return mm.group(0)
        return re.sub(r"(#)?\$([0-9a-f]{1,8})(?![0-9a-f])(\.w|\.l|\(pc)?", rep, ops)

    tmp = tempfile.mkdtemp()
    raw_fallback = []
    lines = ["; generated by m68k_mksrc.py from %s, load address $%x" % (os.path.basename(a.image), a.load),
             "; must reassemble to the same bytes: vasmm68k_mot -Fbin -no-opt", "",
             "\torg\t$%x" % a.load, ""]
    pos = a.load
    end = a.load + len(data)
    while pos < end:
        if pos in targets:
            c = comments.get(pos)
            lines.append("%s:%s" % (label(pos), ("\t; " + c) if c else ""))
        if pos in dis.ins:
            size, m, ops = dis.ins[pos]
            raw = data[pos - a.load:pos - a.load + size]
            vm, vops = vasm_syntax(m, ops)
            text = (vm + "\t" + vops) if vops else vm
            ok = a.check is None or assemble_one(a.check, text, pos, tmp) == raw
            if ok:
                lines.append("\t%s\t%s" % (vm, sub_ops(vops)) if vops else "\t%s" % vm)
            else:
                lines.append("\tdc.w\t%s\t; %s %s" % (",".join("$%02x%02x" % (raw[i], raw[i + 1])
                                                              for i in range(0, size, 2)), m, ops))
                raw_fallback.append((pos, m, ops))
            pos += size
            continue
        b = pos + 1
        while b < end and b not in dis.ins and b not in targets and b - pos < 16:
            b += 1
        chunk = data[pos - a.load:b - a.load]
        lines.append("\tdc.b\t" + ",".join("$%02x" % c for c in chunk))
        pos = b
    open(a.out, "w").write("\n".join(lines) + "\n")
    print("%s: %d instructions, %d emitted as dc.w (vasm differs), %d labels"
          % (a.out, len(dis.ins), len(raw_fallback), len(targets)))
    for pos, m, ops in raw_fallback[:15]:
        print("  dc.w at $%x: %s %s" % (pos, m, ops))
    if a.check:
        out = os.path.join(tmp, "all.bin")
        r = subprocess.run([a.check, "-Fbin", "-no-opt", "-quiet", "-o", out, a.out],
                           stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)
        if r.returncode:
            print(r.stderr[-3000:])
            sys.exit(1)
        got = open(out, "rb").read()
        if got == data:
            print("reassembled: IDENTICAL (%d bytes)" % len(got))
        else:
            diff = next((i for i in range(min(len(got), len(data))) if got[i] != data[i]), None)
            print("reassembled: DIFFERENT, %d vs %d bytes, first difference at $%x"
                  % (len(got), len(data), a.load + (diff if diff is not None else min(len(got), len(data)))))
            sys.exit(1)


if __name__ == "__main__":
    main()
